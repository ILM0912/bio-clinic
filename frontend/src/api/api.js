export const getGroups = () => groups;
export const getBranches = () => branches;

export const getServices = ({ branchId = null, groupId = null } = {}) => {
  return services.filter((service) => {
    const matchesBranch = branchId
      ? service.branches.includes(branchId)
      : true;

    const matchesGroup = groupId
      ? service.group === groupId
      : true;

    return matchesBranch && matchesGroup;
  });
};

export const getService = (id) => {
  return services.find((service) => service.id === Number(id));
};

export const login = (username, password) => {
  const user = users.find(
    (u) => u.username === username && u.password === password
  );

  if (!user) {
    return null;
  }

  return {
    id: user.id,
    username: user.username,
    first_name: user.first_name,
    last_name: user.last_name,
    role: user.role,
  };
};